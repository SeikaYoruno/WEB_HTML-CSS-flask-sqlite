"""
解答2：位置引数とキーワード引数

ねらい：位置引数とキーワード引数を混ぜるときの「並べ方のルール」がわかるようになる
"""

def show_info(name, age, country="日本"):
    print(f"{name}さん（{age}歳）は{country}出身です。")


# 正解は B。
show_info("田中", 30, country="アメリカ")   # 田中さん（30歳）はアメリカ出身です。

# A・C：キーワード引数（country=… / name=…）の後に位置引数を置いているので SyntaxError
# D：エラーにはならないが、位置引数は書いた順に入るので name=30, age="田中" になってしまう
#    → 30さん（田中歳）はアメリカ出身です。
