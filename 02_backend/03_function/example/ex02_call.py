"""
サンプル：関数の呼び出し方（README「2. 関数の定義と呼び出し」）

ねらい：同じ関数を、位置引数・キーワード引数・順番を入れ替えたキーワード引数の3通りで呼び出せることを確かめる
実行：python 02_backend/03_function/example/ex02_call.py
見てほしい出力：3 が3行（どの呼び出し方でも結果は同じ）
"""

def add(a, b):
    print(a + b)


add(1, 2)        # 位置引数：書いた順に a=1, b=2
add(a=1, b=2)    # キーワード引数：名前を指定して渡す
add(b=2, a=1)    # キーワード引数は順番を入れ替えてもよい

# add(b=2, 1)    # コメントを外すと SyntaxError：キーワード引数の後に位置引数は置けない
